import type { Profile } from "./schema";

/**
 * The profile values the site shell needs (spec 0004 AC-12): the root layout's
 * metadata, the header and the footer. They reach the shell through a module
 * generated at build time (`pnpm content:generate`), so a page rendered at request
 * time on Workers never reads `content/`. Pure: no file access here.
 */
export type ShellProfile = Readonly<{
  name: Profile["name"];
  headline: Profile["headline"];
  intro: Profile["intro"];
  email: Profile["email"];
  links: Readonly<Profile["links"]>;
}>;

/** Where the generated module lives, relative to the project root. Gitignored. */
export const SHELL_PROFILE_MODULE_PATH = "src/lib/content/generated/shell-profile.ts";

/** Keeps only the shell's fields, so nothing else from the profile ends up in the module. */
export function toShellProfile(profile: Profile): ShellProfile {
  return {
    name: profile.name,
    headline: profile.headline,
    intro: profile.intro,
    email: profile.email,
    links: { linkedin: profile.links.linkedin, github: profile.links.github },
  };
}

/**
 * The TypeScript source of the generated module: the shell's profile values and the
 * build year (for the footer's copyright line). Values are JSON encoded, so any text is safe.
 */
export function shellProfileModuleSource(profile: ShellProfile, buildYear: number): string {
  return [
    "// Generated by `pnpm content:generate` from content/pages/profile.md (spec 0004 AC-12).",
    "// Do not edit: it is rewritten on every dev, build, lint, typecheck and test run.",
    'import type { ShellProfile } from "../shell-profile";',
    "",
    `export const SHELL_PROFILE: ShellProfile = ${JSON.stringify(profile, null, 2)};`,
    "",
    `export const BUILD_YEAR: number = ${String(Math.trunc(buildYear))};`,
    "",
  ].join("\n");
}
